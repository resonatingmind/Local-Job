const elements = document.querySelectorAll("[data-i18n]");
const english = new Map();
elements.forEach((el) => english.set(el, el.innerHTML));

function setLanguage(lang) {
  const dict = translations[lang];
  elements.forEach((el) => {
    const key = el.dataset.i18n;
    el.innerHTML = dict && dict[key] ? dict[key] : english.get(el);
  });
  document.documentElement.lang = lang;
  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.setAttribute("aria-pressed", String(btn.dataset.lang === lang));
  });
  try { localStorage.setItem("lc-lang", lang); } catch (e) { /* storage unavailable */ }
}

document.querySelectorAll(".lang-switch button").forEach((btn) => {
  btn.addEventListener("click", () => setLanguage(btn.dataset.lang));
});

let saved = null;
try { saved = localStorage.getItem("lc-lang"); } catch (e) { /* storage unavailable */ }
if (saved && saved !== "en") setLanguage(saved);

document.getElementById("year").textContent = new Date().getFullYear();
